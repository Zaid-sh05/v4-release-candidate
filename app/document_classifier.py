AUTHORITY_DEFAULTS = {
    'وزارة العمل': 'labor',
    'دائرة مراقبة الشركات': 'commercial',
    'وزارة الاقتصاد الرقمي': 'cyber',
    'المعهد المروري': 'traffic',
}


def classify_document(title: str, body: str = '', *, source_domains: list[str] | None = None, authority: str = '') -> tuple[str, float, list[str]]:
    nt = normalize_ar(title)
    nb = normalize_ar((body or '')[:18000])

    for domain, phrases in TITLE_RULES:
        hits = [p for p in phrases if normalize_ar(p) in nt]
        if hits:
            return domain, 1.0, [f'title:{x}' for x in hits[:4]]

    # A source with exactly one declared legal domain is a reliable fallback.
    if source_domains and len(source_domains) == 1:
        return source_domains[0], .9, ['source-domain']

    for needle, domain in AUTHORITY_DEFAULTS.items():
        if normalize_ar(needle) in normalize_ar(authority):
            return domain, .82, ['authority-default']

    scores = Counter()
    reasons: dict[str, list[str]] = {}
    for domain, phrases in BODY_HINTS.items():
        reasons[domain] = []
        for p in phrases:
            np = normalize_ar(p)
            if np and np in nb:
                scores[domain] += 1
                reasons[domain].append(p)

    if scores:
        best, score = scores.most_common(1)[0]
        second = scores.most_common(2)[1][1] if len(scores) > 1 else 0
        # Require several body clues and some separation from the runner-up.
        if score >= 3 and (score - second >= 1):
            return best, min(.8, .45 + score * .07), [f'body:{x}' for x in reasons[best][:5]]

    if source_domains:
        # Ambiguous official source: keep the document in general rather than pretending certainty.
        return 'general', .35, ['ambiguous-official-source']
    return 'general', .25, ['no-strong-signal']
