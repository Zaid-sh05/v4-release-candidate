def compact_fact_chunks(chunks):
    grouped={}
    order=[]
    for article,body in chunks:
        key=article
        if key not in grouped:
            grouped[key]=[]; order.append(key)
        b=(body or '').strip()
        if b: grouped[key].append(b)
    out=[]
    for key in order:
        bodies=grouped[key]
        # Keep the most complete verified summary when shorter component facts are already
        # embedded in it. This avoids repetitive answers while preserving evidence.
        keep=[]
        for b in sorted(bodies,key=len,reverse=True):
            nb=' '.join(b.split())
            if any(nb in ' '.join(k.split()) for k in keep):
                continue
            keep.append(b)
        keep=list(reversed(keep))
        out.append((key,' '.join(keep)))
    return out

def reset_fact_document(d):
    import hashlib
    doc_id=hashlib.sha1(f"{d['url']}|{d['title']}|{d['domain']}".encode()).hexdigest()
    with repository.connect() as con:
        con.execute('delete from chunks where document_id=?',(doc_id,))


def seed_registry():
    with repository.connect() as con:
        for rid,ar,en,authority,url,domains,mode,notes in REGISTRY:
            con.execute('''insert into source_registry(id,name_ar,name_en,authority,url,domains_json,sync_mode,notes,last_sync_at,last_sync_status)
                values(?,?,?,?,?,?,?,?,?,?)
                on conflict(id) do update set name_ar=excluded.name_ar,name_en=excluded.name_en,authority=excluded.authority,url=excluded.url,domains_json=excluded.domains_json,sync_mode=excluded.sync_mode,notes=excluded.notes,last_sync_at=excluded.last_sync_at,last_sync_status=excluded.last_sync_status''',
                (rid,ar,en,authority,url,json.dumps(domains,ensure_ascii=False),mode,notes,VERIFIED,'verified'))


def main():
    seed_registry(); total=0
    # Remove stale curated rows from earlier V3 iterations whose title changed.
    stale_titles=['قانون الجرائم الإلكترونية رقم 17 لسنة 2023 — المادة 18']
    with repository.connect() as con:
        for title in stale_titles:
            ids=[r['id'] for r in con.execute('select id from documents where title_ar=?',(title,)).fetchall()]
            for did in ids:
                con.execute('delete from chunks where document_id=?',(did,))
                con.execute('delete from documents where id=?',(did,))
    for d in FACT_DOCS:
        reset_fact_document(d)
        chunks=compact_fact_chunks(d['chunks'])
        n=repository.upsert_document_chunks(title=d['title'],authority=d['authority'],domain=d['domain'],source_url=d['url'],chunks=chunks,source_kind=d['kind'],verified_at=VERIFIED)
        total+=n
        print(f"{d['domain']:16} +{n:2}  {d['title']}")
    # Rebuild the contentless FTS index after replacing curated fact chunks.
    with repository.connect() as con:
        con.execute("insert into chunk_fts(chunk_fts) values('delete-all')")
        rows=con.execute('select c.rowid,d.title_ar,c.body from chunks c join documents d on d.id=c.document_id').fetchall()
        con.executemany('insert into chunk_fts(rowid,title,body) values(?,?,?)',[(r['rowid'],r['title_ar'],r['body']) for r in rows])
    print('verified chunks added:',total)
    print(repository.stats())

if __name__=='__main__': main()
